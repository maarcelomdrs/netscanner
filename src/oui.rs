use pnet::datalink::MacAddr;

pub fn resolve_mac_vendor(mac: MacAddr) -> &'static str {
    let oui = (mac.0, mac.1, mac.2);
    match oui {
        (0xb8, 0x27, 0xeb) | (0xdc, 0xa6, 0x32) | (0xe4, 0x5f, 0x01) | (0x28, 0xcd, 0xc1) => {
            "Raspberry Pi"
        }
        (0x24, 0x0a, 0xc4)
        | (0x30, 0xae, 0xa4)
        | (0x84, 0x0d, 0x8e)
        | (0xa4, 0xcf, 0x12)
        | (0xac, 0x67, 0xb2)
        | (0xbc, 0xdd, 0xc2) => "Espressif (ESP32/8266)",
        (0x00, 0x03, 0x93)
        | (0x00, 0x05, 0x02)
        | (0x00, 0x0a, 0x95)
        | (0x3c, 0x06, 0x30)
        | (0x70, 0x81, 0xeb)
        | (0x88, 0x66, 0x5a)
        | (0xac, 0xde, 0x48) => "Apple",
        (0x50, 0xc7, 0xbf)
        | (0x54, 0xaf, 0x97)
        | (0x60, 0x32, 0xb1)
        | (0x98, 0x48, 0x27)
        | (0xc0, 0x06, 0xc3)
        | (0xc8, 0x3a, 0x35) => "TP-Link",
        (0x00, 0x1b, 0x21)
        | (0x00, 0x13, 0x02)
        | (0x34, 0x13, 0xe8)
        | (0x68, 0x05, 0xca)
        | (0xa4, 0x4e, 0x31)
        | (0xf4, 0x4d, 0x30) => "Intel",
        (0x00, 0xe0, 0x4c) | (0x52, 0x54, 0x00) => "Realtek / QEMU",
        (0x04, 0xd9, 0xf5) | (0x10, 0xbf, 0x48) | (0x70, 0x4d, 0x7b) | (0xf4, 0xb5, 0x20) => {
            "ASUSTeK Computer"
        }
        (0x00, 0x00, 0x0c) | (0x00, 0x01, 0x42) | (0x00, 0x04, 0x4d) | (0x00, 0x1a, 0x2f) => {
            "Cisco"
        }
        (0x00, 0x07, 0xab)
        | (0x08, 0x37, 0x3d)
        | (0x14, 0xbb, 0x6e)
        | (0x34, 0xbe, 0x00)
        | (0x94, 0x65, 0x2d) => "Samsung",
        (0x18, 0xe7, 0xb0)
        | (0x28, 0x6c, 0x07)
        | (0x58, 0x44, 0x98)
        | (0x64, 0x09, 0x80)
        | (0x74, 0x23, 0x44) => "Xiaomi",
        (0x00, 0x1a, 0x11) | (0x3c, 0x5a, 0xb4) | (0x94, 0xeb, 0x2c) | (0xd8, 0x6c, 0x63) => {
            "Google"
        }
        (0x00, 0x14, 0x22) | (0x18, 0x03, 0x73) | (0xd4, 0xbe, 0xd9) | (0xf8, 0xbc, 0x12) => "Dell",
        (0x00, 0x1e, 0x10)
        | (0x04, 0x25, 0x4c)
        | (0x20, 0x0b, 0xc7)
        | (0x48, 0x46, 0xfb)
        | (0x80, 0x2d, 0x1a)
        | (0xc8, 0xa6, 0xef) => "Huawei",
        (0xe0, 0x01, 0xc7) => "C-Data / Chiptrip",
        _ => "Fabricante Desconhecido",
    }
}
